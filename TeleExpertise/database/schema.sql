BEGIN;
CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 email VARCHAR(200) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE nurse (id BIGINT PRIMARY KEY REFERENCES app_user(id));
CREATE TABLE general_practitioner (id BIGINT PRIMARY KEY REFERENCES app_user(id));
CREATE TABLE specialist (
 id BIGINT PRIMARY KEY REFERENCES app_user(id), specialty VARCHAR(100) NOT NULL,
 tariff NUMERIC(10,2) NOT NULL CHECK (tariff >= 0)
);
CREATE TABLE patient (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 birth_date DATE NOT NULL, social_security_number VARCHAR(50) NOT NULL UNIQUE,
 phone VARCHAR(30), address VARCHAR(300), insurance VARCHAR(100),
 history VARCHAR(3000), allergies VARCHAR(1000), current_treatment VARCHAR(3000),
 waiting BOOLEAN NOT NULL DEFAULT TRUE, arrival_at TIMESTAMP NOT NULL
);
CREATE TABLE vital_signs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patient(id), nurse_id BIGINT NOT NULL REFERENCES nurse(id),
 blood_pressure VARCHAR(20) NOT NULL, heart_rate INTEGER NOT NULL CHECK (heart_rate BETWEEN 1 AND 300),
 temperature NUMERIC(4,1) NOT NULL CHECK (temperature BETWEEN 25 AND 45),
 respiratory_rate INTEGER NOT NULL CHECK (respiratory_rate BETWEEN 1 AND 100),
 weight NUMERIC(6,2), height NUMERIC(6,2), recorded_at TIMESTAMP NOT NULL
);
CREATE TABLE consultation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patient(id), doctor_id BIGINT NOT NULL REFERENCES general_practitioner(id),
 reason VARCHAR(1000) NOT NULL, observations VARCHAR(3000), diagnosis VARCHAR(3000), treatment VARCHAR(3000),
 status VARCHAR(50) NOT NULL CHECK (status IN ('EN_COURS','EN_ATTENTE_AVIS_SPECIALISTE','AVIS_RECU','TERMINEE')),
 base_cost NUMERIC(10,2) NOT NULL DEFAULT 150.00 CHECK (base_cost = 150.00), created_at TIMESTAMP NOT NULL
);
CREATE TABLE medical_act (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 consultation_id BIGINT NOT NULL REFERENCES consultation(id), name VARCHAR(200) NOT NULL,
 price NUMERIC(10,2) NOT NULL CHECK (price >= 0)
);
CREATE TABLE expertise_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 consultation_id BIGINT NOT NULL UNIQUE REFERENCES consultation(id),
 specialist_id BIGINT NOT NULL REFERENCES specialist(id), question VARCHAR(3000) NOT NULL,
 priority VARCHAR(30) NOT NULL CHECK (priority IN ('URGENTE','NORMALE','NON_URGENTE')),
 status VARCHAR(30) NOT NULL CHECK (status IN ('EN_ATTENTE','TERMINEE')),
 fee NUMERIC(10,2) NOT NULL CHECK (fee >= 0), opinion VARCHAR(3000), recommendations VARCHAR(3000),
 created_at TIMESTAMP NOT NULL, completed_at TIMESTAMP
);
CREATE TABLE time_slot (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 specialist_id BIGINT NOT NULL REFERENCES specialist(id), starts_at TIMESTAMP NOT NULL,
 status VARCHAR(30) NOT NULL CHECK (status IN ('DISPONIBLE','RESERVE','ARCHIVE'))
);
CREATE INDEX idx_patient_waiting ON patient(waiting, arrival_at);
CREATE INDEX idx_consultation_doctor ON consultation(doctor_id);
CREATE INDEX idx_vitals_patient ON vital_signs(patient_id);
CREATE INDEX idx_expertise_specialist ON expertise_request(specialist_id);
COMMIT;
